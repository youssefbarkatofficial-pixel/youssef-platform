const fs = require('fs');

const titleFixes = [
    // titles
    ['إدارة الكورسات - لوحة الإدارة', 'إدارة الكورسات - لوحة الإدارة'],
    ['لوحة الإدارة | يوسف بركات', 'لوحة الإدارة | يوسف بركات'],
    ['مراجعة المدفوعات - لوحة الإدارة', 'مراجعة المدفوعات - لوحة الإدارة'],
    ['تحليلات الطلاب التفصيلية - لوحة الإدارة', 'تحليلات الطلاب التفصيلية - لوحة الإدارة'],
    ['إدارة الطلاب - لوحة الإدارة', 'إدارة الطلاب - لوحة الإدارة'],
    ['الرفع السريع - لوحة الإدارة', 'الرفع السريع - لوحة الإدارة'],
    ['صراع البوصلة - المنصة التعليمية', 'صراع البوصلة - المنصة التعليمية'],
    ['تفاصيل الكورس | منصة يوسف بركات للدراسات الاجتماعية', 'تفاصيل الكورس | منصة يوسف بركات للدراسات الاجتماعية'],
    ['لوحة التحكم | منصة يوسف بركات', 'لوحة التحكم | منصة يوسف بركات'],
    ['إصلاح الإشعارات', 'إصلاح الإشعارات'],
    ['إنشاط، حساب جديد | منصة يوسف بركات', 'إنشاء حساب جديد | منصة يوسف بركات'],
    ['الإحصائيات - منصة يوسف بركات', 'الإحصائيات - منصة يوسف بركات'],
    ['الدعم الفني - منصة يوسف بركات', 'الدعم الفني - منصة يوسف بركات'],
    
    // extra meta or body found in those files
    ['منصة يوسف بركات للدراسات الاجتماعية', 'منصة يوسف بركات للدراسات الاجتماعية'],
    ['تعلم التاريخ والجط؛رافيا بطريقة احترافية مع منصة يوسف بركات التعليمية.', 'تعلم التاريخ والجغرافيا بطريقة احترافية مع منصة يوسف بركات التعليمية.'],
    ['التاريخ', 'التاريخ'],
    ['الجط؛رافيا', 'الجغرافيا']
];

const files = fs.readdirSync('.').filter(f => f.endsWith('.html'));

let fixedCount = 0;
files.forEach(file => {
    let content = fs.readFileSync(file, 'utf8');
    let changed = false;
    
    for (const [bad, good] of titleFixes) {
        if (content.includes(bad)) {
            content = content.split(bad).join(good);
            changed = true;
        }
    }
    
    if (changed) {
        fs.writeFileSync(file, content, 'utf8');
        console.log(`✅ Fixed meta in: ${file}`);
        fixedCount++;
    }
});

console.log(`Fixed ${fixedCount} files.`);
