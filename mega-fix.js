const allFiles = [
    ...fs.readdirSync('.').filter(f => (f.endsWith('.html') || f.endsWith('.js')) && !f.includes('.tmp')),
    ...fs.readdirSync('js').map(f => 'js/'+f).filter(f => f.endsWith('.js')),
    ...fs.readdirSync('css').map(f => 'css/'+f).filter(f => f.endsWith('.css')),
];

let totalFixed = 0;
for (const file of allFiles) {
    try {
        let content = fs.readFileSync(file, 'utf8');
        let changed = false;
        for (const [bad, good] of arabicFixes) {
            if (content.includes(bad)) {
                content = content.split(bad).join(good);
                changed = true;
            }
        }
        if (changed) {
            fs.writeFileSync(file, content, 'utf8');
            totalFixed++;
            console.log(`✅ ${file}`);
        }
    } catch(e) {}
}
console.log(`\n🔤 Arabic fixes: ${totalFixed} files`);
