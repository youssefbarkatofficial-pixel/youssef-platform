// ============================================================
//  مولد عناصر التقييم بالذكاء الاصطناعي 🧠✨
// ============================================================

export async function generateRubricFromModelAnswer(modelAnswer, callAI) {
    if (!modelAnswer || modelAnswer.trim().length < 5) {
        throw new Error("الإجابة النموذجية قصيرة جداً لتوليد عناصر تقييم.");
    }

    const prompt = `أنت خبير في وضع نماذج الإجابة (Rubrics) وتصحيح الامتحانات.
لديك هذه الإجابة النموذجية لسؤال مقالي:
"${modelAnswer}"

مهمتك:
1. استخرج أهم "المفاهيم" أو "الأفكار الرئيسية" الموجودة في هذه الإجابة، والتي يجب أن يذكرها الطالب ليحصل على الدرجة النهائية.
2. لكل مفهوم، اقترح مرادفات (synonyms) أو طرق أخرى صحيحة للتعبير عنه.
3. أعطِ كل مفهوم وزناً (weight) كنسبة من الدرجة (مثلاً 1 أو 2).
4. أعد النتيجة كـ مصفوفة JSON فقط بالشكل التالي دون أي نصوص إضافية:
[
  { "concept": "اسم المفهوم الأول", "synonyms": ["مرادف1", "مرادف2"], "weight": 1 },
  { "concept": "اسم المفهوم الثاني", "synonyms": ["مرادف1", "مرادف2"], "weight": 1 }
]`;

    try {
        const raw = await callAI(prompt);
        // استخراج مصفوفة JSON من الرد
        const match = raw.match(/\[[\s\S]*\]/);
        if (!match) throw new Error("لم يتم العثور على مصفوفة JSON في رد الذكاء الاصطناعي.");
        
        const rubric = JSON.parse(match[0]);
        return rubric;
    } catch (e) {
        console.error("فشل توليد عناصر التقييم:", e);
        throw e;
    }
}
